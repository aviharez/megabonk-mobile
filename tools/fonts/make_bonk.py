SPACE_ADVANCE = 4
GAP = 1  # px between letters
CAP = 7
LINE = 10
BASE = 8  # one clear row above the caps, like the small font
WHITE = (0xFF, 0xFF, 0xFF, 0xFF)


def png(path, w, h, pixels):
    raw = b"".join(b"\x00" + b"".join(bytes(pixels[y * w + x]) for x in range(w)) for y in range(h))
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "fonts")
    keys = list(GLYPHS)
    page_w = 128
    x = y = 0
    places = {}
    for k in keys:
        w = len(GLYPHS[k][0])
        assert all(len(r) == w for r in GLYPHS[k]) and len(GLYPHS[k]) == CAP, k
        if x + w > page_w:
            x = 0
            y += CAP + 1
        places[k] = (x, y, w)
        x += w + 1
    page_h = y + CAP + 1
    page_h = 1 << (page_h - 1).bit_length()
    pixels = [(0, 0, 0, 0)] * (page_w * page_h)
    for k, (gx, gy, w) in places.items():
        for r, row in enumerate(GLYPHS[k]):
            for c, ch in enumerate(row):
                if ch == "#":
                    pixels[(gy + r) * page_w + gx + c] = WHITE
    png(os.path.join(root, "bonk.png"), page_w, page_h, pixels)

    chars = [f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset={BASE - CAP} xadvance={SPACE_ADVANCE} page=0 chnl=15"]
    for k, (gx, gy, w) in places.items():
        ids = [ord(k)]
        if k.isalpha():
            ids.append(ord(k.lower()))
        for i in ids:
            chars.append(f"char id={i} x={gx} y={gy} width={w} height={CAP} xoffset=0 yoffset={BASE - CAP} xadvance={w + GAP} page=0 chnl=15")
    lines = [
        'info face="Bonk" size=8 bold=1 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={LINE} base={BASE} scaleW={page_w} scaleH={page_h} pages=1 packed=0",
        'page id=0 file="bonk.png"',
        f"chars count={len(chars)}",
    ] + chars
    with open(os.path.join(root, "bonk.fnt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"bonk: {len(places)} glyphs, page {page_w}x{page_h}")


if __name__ == "__main__":
    main()
